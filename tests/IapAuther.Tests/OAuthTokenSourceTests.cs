    [Fact]
    public async Task BrowserFlow_NoBrowserLogOutputStdout_WritesPromptsOnlyToStdout()
    {
        var expectedJwt = CachedTokenSourceTests.MakeJwt(DateTimeOffset.UtcNow.AddHours(1));
        using var outWriter = new SignalingStringWriter();
        using var errWriter = new StringWriter();
        using var handler = new FakeTokenEndpointHandler(expectedJwt, "rt-789");
        var logger = new StderrLogger(AppLogLevel.Warn, LogOutputMode.Stdout, errWriter, outWriter);

        using var source = new OAuthTokenSource(
            "client-id.apps.googleusercontent.com",
            "client-secret",
            noBrowser: true,
            logger: logger,
            store: new RefreshTokenStore(_tempDir),
            httpMessageHandler: handler);

        var tokenTask = source.GetTokenAsync().AsTask();
        var authUrl = await outWriter.WaitForAuthUrlAsync().WaitAsync(TimeSpan.FromSeconds(5));
        await TriggerLoopbackCallbackAsync(authUrl);

        var token = await tokenTask;
        Assert.Equal(expectedJwt, token);
        Assert.Equal(string.Empty, errWriter.ToString());

        var stdout = outWriter.ToString();
        Assert.Contains("iap-auther: Google sign-in required.", stdout);
        Assert.Contains("Visit this URL to sign in:", stdout);
    }

    [Fact]
    public async Task StoredRefreshToken_RefreshesWithoutBrowser_AndUpdatesRotatedToken()
    {
        var expectedJwt = CachedTokenSourceTests.MakeJwt(DateTimeOffset.UtcNow.AddHours(1));
        var store = new RefreshTokenStore(_tempDir);
        store.Save("client-id.apps.googleusercontent.com", "rt-initial");

        using var handler = new FakeTokenEndpointHandler(expectedJwt, "rt-rotated");
        var browserCalled = false;

        using var source = new OAuthTokenSource(
            "client-id.apps.googleusercontent.com",
            "client-secret",
            store: store,
            httpMessageHandler: handler,
            browserLauncher: _ => browserCalled = true);

        var token = await source.GetTokenAsync();

        Assert.False(browserCalled);
        Assert.Equal(expectedJwt, token);
        Assert.Equal("rt-rotated", store.Load("client-id.apps.googleusercontent.com"));

        var form = Assert.Single(handler.RecordedForms);
        Assert.Equal("refresh_token", form["grant_type"]);
        Assert.Equal("rt-initial", form["refresh_token"]);
    }

    [Fact]
    public async Task StoredRefreshTokenRejected_FallsBackToBrowserFlowAndUpdatesStore()
    {
        var expectedJwt = CachedTokenSourceTests.MakeJwt(DateTimeOffset.UtcNow.AddHours(1));
        var store = new RefreshTokenStore(_tempDir);
        store.Save("client-id.apps.googleusercontent.com", "rt-expired");

        using var errWriter = new StringWriter();
        var logger = new StderrLogger(AppLogLevel.Warn, LogOutputMode.Stderr, errWriter);
        using var handler = new FakeTokenEndpointHandler(form =>
            form["grant_type"] == "refresh_token"
                ? FakeTokenEndpointHandler.CreateJsonResponse(HttpStatusCode.BadRequest, new
                {
                    error = "invalid_grant",
                    error_description = "Token has been expired or revoked.",
                })
                : FakeTokenEndpointHandler.CreateJsonResponse(HttpStatusCode.OK, new
                {
                    id_token = expectedJwt,
                    refresh_token = "rt-fresh",
                }));

        Task? callbackTask = null;
        using var source = new OAuthTokenSource(
            "client-id.apps.googleusercontent.com",
            "client-secret",
            logger: logger,
            store: store,
            httpMessageHandler: handler,
            browserLauncher: authUrl => callbackTask = TriggerLoopbackCallbackAsync(authUrl));

        var token = await source.GetTokenAsync();
        Assert.NotNull(callbackTask);
        await callbackTask!;

        Assert.Equal(expectedJwt, token);
        Assert.Equal("rt-fresh", store.Load("client-id.apps.googleusercontent.com"));
        Assert.Equal(2, handler.RecordedForms.Count);
        Assert.Contains("Stored refresh token rejected", errWriter.ToString());
    }

    [Fact]
    public async Task BrowserFlow_StateMismatch_ThrowsAuthException()
    {
        using var outWriter = new StringWriter();
        using var errWriter = new StringWriter();
        using var handler = new FakeTokenEndpointHandler("unused-jwt", "unused-rt");
        var logger = new StderrLogger(AppLogLevel.Warn, LogOutputMode.Stderr, errWriter, outWriter);

        Task? callbackTask = null;
        using var source = new OAuthTokenSource(
            "client-id.apps.googleusercontent.com",
