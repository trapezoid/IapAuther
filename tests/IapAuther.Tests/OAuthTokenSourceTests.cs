    private sealed class FakeTokenEndpointHandler : HttpMessageHandler
    {
        private readonly Func<NameValueCollection, HttpResponseMessage> _responder;

        public FakeTokenEndpointHandler(string idToken, string? refreshToken = null)
            : this(_ => CreateJsonResponse(HttpStatusCode.OK, new
            {
                id_token = idToken,
                refresh_token = refreshToken,
            }))
        {
        }

        public FakeTokenEndpointHandler(Func<NameValueCollection, HttpResponseMessage> responder)
        {
            _responder = responder;
        }

        public List<NameValueCollection> RecordedForms { get; } = [];

        protected override async Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken cancellationToken)
        {
            var body = request.Content is null
                ? string.Empty
                : await request.Content.ReadAsStringAsync(cancellationToken);
            var form = HttpUtility.ParseQueryString(body);
            RecordedForms.Add(form);
            return _responder(form);
        }

        public static HttpResponseMessage CreateJsonResponse(HttpStatusCode status, object payload) =>
            new(status)
            {
                Content = new StringContent(JsonSerializer.Serialize(payload), Encoding.UTF8, "application/json"),
            };
    }

    private sealed class SignalingStringWriter : StringWriter
    {
        private readonly TaskCompletionSource<string> _authUrlTcs = new(TaskCreationOptions.RunContinuationsAsynchronously);

        public Task<string> WaitForAuthUrlAsync() => _authUrlTcs.Task;

        public override void WriteLine(string? value)
        {
            base.WriteLine(value);
            if (value is null)
            {
                return;
            }
            foreach (var line in value.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            {
                if (line.StartsWith("https://accounts.google.com/o/oauth2/v2/auth?", StringComparison.Ordinal))
                {
                    _authUrlTcs.TrySetResult(line);
                }
            }
        }
    }

    [Fact]
    public async Task BrowserFlow_DefaultStderrLogger_WritesPromptsOnlyToStderr()
    {
        var expectedJwt = CachedTokenSourceTests.MakeJwt(DateTimeOffset.UtcNow.AddHours(1));
        using var outWriter = new StringWriter();
        using var errWriter = new StringWriter();
        using var handler = new FakeTokenEndpointHandler(expectedJwt, "rt-123");
        var store = new RefreshTokenStore(_tempDir);
        var logger = new StderrLogger(AppLogLevel.Info, LogOutputMode.Stderr, errWriter, outWriter);

        string? capturedAuthUrl = null;
        Task? callbackTask = null;
        using var source = new OAuthTokenSource(
            "client-id.apps.googleusercontent.com",
            "client-secret",
            noBrowser: false,
            logger: logger,
            store: store,
            httpMessageHandler: handler,
            browserLauncher: authUrl =>
            {
                capturedAuthUrl = authUrl;
                callbackTask = TriggerLoopbackCallbackAsync(authUrl);
            });

        var token = await source.GetTokenAsync();
        Assert.NotNull(callbackTask);
        await callbackTask!;

        Assert.Equal(expectedJwt, token);
        Assert.Equal(string.Empty, outWriter.ToString());
        Assert.Equal("rt-123", store.Load("client-id.apps.googleusercontent.com"));

        // Verify PKCE S256 & Google OAuth parameters generated by PkceGoogleAuthorizationCodeFlow.
        Assert.NotNull(capturedAuthUrl);
        var authQuery = HttpUtility.ParseQueryString(new Uri(capturedAuthUrl!).Query);
        Assert.Equal("offline", authQuery["access_type"]);
        Assert.Equal("consent", authQuery["prompt"]);
        Assert.Equal("S256", authQuery["code_challenge_method"]);
        Assert.Equal("openid email", authQuery["scope"]);
        Assert.EndsWith("/authorize/", authQuery["redirect_uri"]);
        Assert.False(string.IsNullOrEmpty(authQuery["state"]));

        var form = Assert.Single(handler.RecordedForms);
        Assert.Equal("authorization_code", form["grant_type"]);
        Assert.Equal("test-auth-code", form["code"]);
        Assert.Equal(authQuery["redirect_uri"], form["redirect_uri"]);
        var verifier = form["code_verifier"];
        Assert.False(string.IsNullOrEmpty(verifier));
        var expectedChallenge = JwtUtils.EncodeBase64Url(SHA256.HashData(Encoding.ASCII.GetBytes(verifier!)));
        Assert.Equal(expectedChallenge, authQuery["code_challenge"]);

        var stderr = errWriter.ToString();
        Assert.Contains("iap-auther: Google sign-in required.", stderr);
        Assert.Contains("Opening browser for Google sign-in. If it does not open, visit:", stderr);
        Assert.Contains("https://accounts.google.com/o/oauth2/v2/auth?", stderr);
        Assert.Contains("level=INFO", stderr);
    }

